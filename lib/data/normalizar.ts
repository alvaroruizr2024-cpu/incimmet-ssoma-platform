import type {
  AccionLectura,
  BaseNormalizada,
  DataJson,
  EventoLectura,
  LeccionLectura,
  NivelIncimmet,
  ReporteLocal,
} from '../types';
const niveles: readonly string[] = ['0', 'I', 'II', 'III', 'IV', 'V', 'VI'];
/** Copia de lectura sin alterar fechas, clasificaciones, ortografía o agregados oficiales. */
export function normalizarDocumento(data: DataJson): BaseNormalizada {
  const d = structuredClone(data);
  const eventos: EventoLectura[] = d.eventos.map((e) => ({
    id: e.id,
    fecha: e.fecha,
    hora: e.hora,
    anio: e.anio,
    mes: e.mes,
    proyectoCodigo: e.proyecto,
    cliente: e.cliente,
    puestoRol: e.puesto_rol,
    area: e.area ?? undefined,
    actividad: e.actividad ?? undefined,
    equipo: e.equipo ?? undefined,
    tipo: e.tipo,
    tipoGrupo: e.tipo_grupo,
    nivelIncimmet:
      e.nivel_incimmet !== null && niveles.includes(e.nivel_incimmet)
        ? (e.nivel_incimmet as NivelIncimmet)
        : undefined,
    pgIncimmet: e.pg_incimmet ?? undefined,
    nivelCliente: e.nivel_cliente ?? undefined,
    pgCliente: e.pg_cliente ?? undefined,
    altoPotencial: e.alto_potencial,
    riesgoCritico: e.riesgo_critico ?? undefined,
    descripcion: e.descripcion,
    estadoOrigen: e.estado,
    estado: e.estado && /investigaci[oó]n/i.test(e.estado) ? 'En investigación' : null,
    diasPerdidos: e.dias_perdidos ?? undefined,
    costo: e.costo ?? undefined,
    penalidad: e.penalidad ?? undefined,
    empresaTipo: e.empresa_tipo,
    confianza: e.confianza,
    creadoPor: null,
    creadoEn: null,
    causasInmediatas: e.causas_inmediatas,
    causasBasicas: e.causas_basicas,
    fuentes: e.fuentes,
    leccionIds: e.lecciones,
    origen: 'documental',
    original: e,
  }));
  const acciones: AccionLectura[] = d.acciones.map((a) => ({
    id: a.id,
    eventoId: a.evento_id,
    proyectoCodigo: a.proyecto,
    descripcion: a.descripcion,
    tipo: a.tipo,
    jerarquia: a.jerarquia_control,
    alcance: a.alcance,
    responsableRol: a.responsable_rol,
    fechaCompromiso: a.fecha_compromiso ?? undefined,
    estadoDeclarado: a.estado_declarado ?? undefined,
    fechaEstadoDeclarado: a.fecha_estado_declarado ?? undefined,
    estadoVerificado: a.estado_verificado,
    estadoImportado: a.estado_verificado,
    estadoOperativo: null,
    referenciasEvidencia: a.evidencias,
    coberturaParcial: /evidencia parcial/i.test(a.observaciones ?? ''),
    fuente: a.fuente,
    observaciones: a.observaciones,
    original: a,
  }));
  const lecciones: LeccionLectura[] = d.lecciones.map((l) => ({
    id: l.id,
    eventoIds: l.eventos,
    proyectoCodigos: l.proyectos,
    quePaso: l.que_paso,
    porQue: l.por_que,
    leccion: l.leccion,
    controles: {
      eliminacion: l.controles.eliminacion ?? undefined,
      sustitucion: l.controles.sustitucion ?? undefined,
      ingenieria: l.controles.ingenieria ?? undefined,
      administrativos: l.controles.administrativos ?? undefined,
      epp: l.controles.epp ?? undefined,
    },
    actividadCritica: l.actividad_critica,
    riesgoCritico: l.riesgo_critico,
    aplicabilidad: l.aplicabilidad,
    fuentes: l.fuentes,
    publicacion: 'Catalogada',
    original: l,
  }));
  return {
    meta: d.meta,
    catalogos: d.catalogos,
    proyectos: d.proyectos,
    eventos,
    acciones,
    lecciones,
    indicadores: d.indicadores,
    documentosFuente: d.documentos_fuente,
  };
}
export function normalizarReporte(r: ReporteLocal): EventoLectura {
  const p = r.payload;
  return {
    id: r.id,
    fecha: p.fecha,
    hora: p.hora,
    anio: Number(p.fecha.slice(0, 4)),
    mes: Number(p.fecha.slice(5, 7)),
    proyectoCodigo: p.proyectoCodigo,
    cliente: r.cliente,
    area: p.area,
    actividad: p.actividad ?? undefined,
    equipo: p.equipo ?? undefined,
    tipo: p.tipo,
    tipoGrupo: p.tipoGrupo,
    altoPotencial: p.altoPotencial,
    riesgoCritico: p.riesgoCritico ?? undefined,
    descripcion: p.descripcion,
    estado: 'Reportado',
    estadoOrigen: null,
    puestoRol: null,
    empresaTipo: 'No consta',
    creadoPor: `demo:${r.rol}`,
    creadoEn: r.creadoEn,
    causasInmediatas: null,
    causasBasicas: null,
    fuentes: [],
    leccionIds: [],
    origen: 'local',
    original: null,
  };
}
